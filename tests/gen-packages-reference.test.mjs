import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { gzipSync } from "node:zlib";
import { describe, test } from "node:test";
import {
  exportedNames,
  OUT,
  reexportedPackages,
  render,
  typesEntry,
  untar,
} from "../scripts/gen-packages-reference.mjs";
import { privateFindings } from "../scripts/validate-skills.mjs";

/** A ustar archive of the given files under `package/`, gzipped like an npm tarball. */
function tarball(files) {
  const blocks = [];
  for (const [name, text] of Object.entries(files)) {
    const body = Buffer.from(text);
    const header = Buffer.alloc(512);
    header.write(`package/${name}`, 0);
    header.write(body.length.toString(8).padStart(11, "0"), 124);
    header.write("0", 156);
    blocks.push(header, body, Buffer.alloc((512 - (body.length % 512)) % 512));
  }
  return gzipSync(Buffer.concat([...blocks, Buffer.alloc(1024)]));
}

describe("the packages reference", () => {
  const files = untar(
    tarball({
      "dist/index.d.ts":
        "export * from './core.js';\nexport { Provider, type Props } from './react.js';\nexport * from '@tanstack/react-query';\n",
      "dist/core.d.ts":
        "declare function krizakaFetch(): void;\nexport { krizakaFetch, createClient as makeClient };\nexport type { Hidden };\n",
    }),
  );

  test("untar reads the files without the package/ prefix", () => {
    assert.deepEqual([...files.keys()], ["dist/index.d.ts", "dist/core.d.ts"]);
  });

  test("value names follow relative export-star, types are left out", () => {
    assert.deepEqual(exportedNames(files, "dist/index.d.ts"), ["krizakaFetch", "makeClient", "Provider"]);
  });

  test("a whole external package re-exported is named", () => {
    assert.deepEqual(reexportedPackages(files, "dist/index.d.ts"), ["@tanstack/react-query"]);
  });

  test("the types entry comes from exports first, then types", () => {
    assert.equal(typesEntry({ exports: { ".": { types: "./dist/a.d.ts" } }, types: "./b.d.ts" }), "dist/a.d.ts");
    assert.equal(typesEntry({ types: "./b.d.ts" }), "b.d.ts");
  });

  test("render is deterministic and lists entry points and exports", () => {
    const text = render([
      {
        name: "@krizaka/x",
        version: "1.0.0",
        description: "Does x.",
        entries: [".", "./node"],
        names: ["a"],
        reexports: [],
      },
    ]);
    assert.match(text, /## @krizaka\/x 1\.0\.0/);
    assert.match(text, /Entry points: `@krizaka\/x\/node`/);
    assert.match(text, /Exports: `a`/);
    assert.equal(
      text,
      render([
        {
          name: "@krizaka/x",
          version: "1.0.0",
          description: "Does x.",
          entries: [".", "./node"],
          names: ["a"],
          reexports: [],
        },
      ]),
    );
  });

  test("the committed reference is generated, public-safe and covers the core packages", () => {
    const text = readFileSync(OUT, "utf8");
    assert.match(text, /Generated by scripts\/gen-packages-reference\.mjs/);
    assert.deepEqual(privateFindings(text, "packages.md"), []);
    for (const name of [
      "@krizaka/storage",
      "@krizaka/query",
      "@krizaka/intl",
      "@krizaka/time",
      "@krizaka/settings",
      "@krizaka/rate-limit",
    ]) {
      assert.match(text, new RegExp(`## ${name} `), name);
    }
  });
});
